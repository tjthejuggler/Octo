/**
 * Interactive vector body map of the octopus-man (Phase 6 centerpiece).
 *
 * All path data lives in [OctopusBodyGeometry] (generated by scripts/gen_body_geometry.py);
 * this composable only renders + hit-tests. Rendering contract:
 *  - region not stretched today → muted deep-sea slate ([RegionIdle])
 *  - region stretched today → animated teal→green lerp ([RegionTeal]→[RegionGreen]);
 *    intensity scales with minutes (capped at [FULL_INTENSITY_MINUTES]) + pulsing glow
 *  - the HEAD is the PPQ-generated art (Phase 18 correction): the vector dome's
 *    face + 8 hair tentacles are NOT drawn anymore — [R.drawable.octo_head_ppq]
 *    (the same art as the launcher icon, from docs/art/octo_head_raw.png) is
 *    composited over the NECK dome instead. The NECK region path stays in the
 *    hit-test list (tap → part/neck still fires) and is filled ONLY when
 *    stretched/video-targeted, with a glow ring traced OVER the art for feedback.
 *  - muscle lines + limb suction cups drawn last for the cute look
 * Tap any region → [onRegionTap]; the caller owns the tooltip/dialog.
 *
 * Hit-testing is untouched by the head art: the image is drawn inside this
 * Canvas's draw block (no separate pointer-consuming node), so taps over the
 * head still reach the pointerInput below and resolve against the invisible
 * NECK region path.
 */
@Composable
fun OctopusBodyView(
    stretchedMinutes: Map<BodyPart, Int>,
    onRegionTap: (BodyPart) -> Unit,
    modifier: Modifier = Modifier,
    videoTargets: Set<BodyPart> = emptySet(),
    side: OctopusBodyGeometry.Side = OctopusBodyGeometry.Side.FRONT,
    /**
     * Phase 26 (FB26): letterbox mode for fixed-size containers (video-detail
     * side-by-side card). When true the view FILLS the incoming constraints and
     * scales the canvas with min(w/W, h/H), centering it — guarantees both figures
     * render at identical size, fully visible (no bottom clipping), and centered
     * in their half. Default false keeps the dashboard's width-driven layout.
     */
    fitInside: Boolean = false,
    /**
     * Muscle overlay mode (replaces the retired écorché MuscleFigureView): the
     * SAME octopus body renders dulled (dark scrim clipped to the figure) with
     * the exact-muscle plates from [MuscleBodyGeometry] composited on top —
     * both share the 1000x1500 viewBox, so the plates align with the octo-man.
     * Taps resolve against the muscle plates first (via [onMuscleTap]), then
     * fall through to the body-part regions.
     */
    muscleMode: Boolean = false,
    stretchedMuscles: Set<Muscle> = emptySet(),
    onMuscleTap: (Muscle) -> Unit = {},
) {
    // Parse once per composition lifetime — PathParser is cheap but not free.
    // Hit-test regions are built once too (Compose Path has no contains(); the
    // android.graphics.Region route is the standard exact-bounds solution).
    // Phase 20: the region set is per-side — front-only parts (chest, core,
    // groin_adductors, quads) simply do not exist on the BACK figure, so they
    // are never rendered, hit-tested, or amber-highlighted from the back.
    val parsed = remember(side) {
        OctopusBodyGeometry.regionsFor(side).map { spec ->
            val androidPath = PathParser.createPathFromPathData(spec.pathData)
            val bounds = android.graphics.RectF()
            androidPath.computeBounds(bounds, /* exact = */ true)
            val region = android.graphics.Region()
            region.setPath(
                androidPath,
                android.graphics.Region(
                    bounds.left.toInt() - HITTEST_PAD,
                    bounds.top.toInt() - HITTEST_PAD,
                    bounds.right.toInt() + HITTEST_PAD,
                    bounds.bottom.toInt() + HITTEST_PAD,
                ),
            )
            spec to HitTarget(
                path = androidPath.asComposePath(),
                region = region,
            )
        }
    }
    val muscleLines = remember(side) {
        OctopusBodyGeometry.muscleLinesFor(side).map {
            PathParser.createPathFromPathData(it.pathData).asComposePath()
        }
    }
    // Decorative tentacle-finger clusters at the limb ends (in front of the
    // wrist/ankle region tips). The HEAD tentacles are no longer drawn — the
    // PPQ head art's own tentacles are the character's hair (Phase 18).
    val fingerTentacles = remember {
        OctopusBodyGeometry.fingerTentacles.map {
            PathParser.createPathFromPathData(it.pathData).asComposePath()
        }
    }
    // Phase 18: suction cups riding on the (no longer drawn) head tentacles
    // are suppressed; only the limb cups below the head zone remain.
    val limbCups = remember {
        OctopusBodyGeometry.suctionCups.filter { it.cy >= HEAD_ART_BOTTOM_ROW }
    }
    // Muscle overlay plates (parsed only when muscle mode is on).
    val muscleRegions: List<Triple<Muscle, Path, String>> = remember(side, muscleMode) {
        if (!muscleMode) {
            emptyList()
        } else {
            val muscleSide = if (side == OctopusBodyGeometry.Side.BACK) {
                MuscleBodyGeometry.Side.BACK
            } else {
                MuscleBodyGeometry.Side.FRONT
            }
            MuscleBodyGeometry.musclesFor(muscleSide).mapNotNull { spec ->
                val muscle = Muscle.fromId(spec.muscleId) ?: return@mapNotNull null
                val path = runCatching {
                    PathParser.createPathFromPathData(spec.pathData)?.asComposePath()
                }.getOrNull() ?: return@mapNotNull null
                Triple(muscle, path, spec.hue)
            }
        }
    }

    // The head: PPQ-generated octopus art (same source as the launcher icon).
    // Decoded once per composition; cached in memory across recompositions.
    // Phase 21 addendum: the BACK side composites its own PPQ art (smooth mantle,
    // no face) so the man actually looks different from behind.
    val context = LocalContext.current
    val headBitmap = remember(side) {
        val res = if (side == OctopusBodyGeometry.Side.BACK) {
            R.drawable.octo_head_ppq_back
        } else {
            R.drawable.octo_head_ppq
        }
        BitmapFactory.decodeResource(context.resources, res).asImageBitmap()
    }
    val headArt = if (side == OctopusBodyGeometry.Side.BACK) BackHeadArt else FrontHeadArt

    // One animated color per region (≤16 — cheap). Hoisted here because
    // animateColorAsState is composable-level and DrawScope is not.
    val animatedColors: Map<BodyPart, Color> = parsed.associate { (spec, _) ->
        val minutes = stretchedMinutes[spec.part] ?: 0
        val target = regionColor(minutes, spec.part in videoTargets)
        spec.part to animateColorAsState(
            targetValue = target,
            animationSpec = tween(durationMillis = 650),
            label = "region_${spec.part.id}",
        ).value
    }

    // Subtle bioluminescent pulse on stretched regions.
    val pulse = rememberInfiniteTransition(label = "octoPulse")
    val pulseAlpha by pulse.animateFloat(
        initialValue = 0.45f,
        targetValue = 1f,
        animationSpec = infiniteRepeatable(tween(1400), RepeatMode.Reverse),
        label = "pulseAlpha",
    )

    val stretchedCount = stretchedMinutes.size
    val a11yDescription = "Octopus body map: $stretchedCount of 16 regions stretched today. " +
        "Tap a body part to see today's stretch minutes."

    // Phase 24 flip-centering: shift the drawing so this side's VISUAL center
    // (paths ∪ placed head art) sits on the canvas center — the flip pivot.
    val centeringOffsetX = remember(side) { sideCenteringOffsetX(side) }

    // Phase 26 (FB26): in fitInside mode the canvas FILLS the incoming constraints
    // (no aspectRatio forcing the height) and draws letterboxed at
    // min(w/W, h/H) so the whole figure stays visible in fixed-height cards.
    if (fitInside) {
        Canvas(
            modifier = modifier
                .semantics { contentDescription = a11yDescription }
                .pointerInput(parsed, centeringOffsetX, muscleRegions) {
                    detectTapGestures { tap ->
                        val s = min(
                            size.width.toFloat() / OctopusBodyGeometry.CANVAS_WIDTH,
                            size.height.toFloat() / OctopusBodyGeometry.CANVAS_HEIGHT,
                        )
                        // Letterbox centers the drawing in both axes.
                        val dx = (size.width - OctopusBodyGeometry.CANVAS_WIDTH * s) / 2f
                        val dy = (size.height - OctopusBodyGeometry.CANVAS_HEIGHT * s) / 2f
                        // Drawing is shifted left by centeringOffsetX — invert for hit-test.
                        val x = ((tap.x - dx) / s + centeringOffsetX).toInt()
                        val y = ((tap.y - dy) / s).toInt()
                        // Muscle plates first (muscle mode), then body-part regions.
                        if (muscleRegions.isNotEmpty()) {
                            val hit = muscleRegions.lastOrNull { (_, path, _) ->
                                spindleHit(path, x.toFloat(), y.toFloat())
                            }
                            if (hit != null) {
                                onMuscleTap(hit.first)
                                return@detectTapGestures
                            }
                        }
                        for ((spec, hit) in parsed.asReversed()) {
                            if (hit.region.contains(x, y)) {
                                onRegionTap(spec.part)
                                return@detectTapGestures
                            }
                        }
                    }
                },
        ) {
            val s = min(
                size.width / OctopusBodyGeometry.CANVAS_WIDTH,
                size.height / OctopusBodyGeometry.CANVAS_HEIGHT,
            )
            val dx = (size.width - OctopusBodyGeometry.CANVAS_WIDTH * s) / 2f
            val dy = (size.height - OctopusBodyGeometry.CANVAS_HEIGHT * s) / 2f
            translate(left = dx, top = dy) {
                // FB26 fix: pivot MUST be the top-left — DrawScope.scale defaults to
                // the CENTER of the (non-aspect-matched) cell, which shifted the whole
                // drawing right + down and clipped the figures at the card bottom
                // (dx/dy letterbox math and the hit-test inverse both assume top-left).
                // The dashboard branch is unaffected: in an aspect-matched view the
                // center pivot coincides with the canvas center.
                scale(s, s, pivot = Offset.Zero) {
                    translate(left = -centeringOffsetX) {
                        drawBody(
                            animatedColors = animatedColors,
                            stretchedMinutes = stretchedMinutes,
                            videoTargets = videoTargets,
                            pulseAlpha = pulseAlpha,
                            fingerTentacles = fingerTentacles,
                            muscleLines = muscleLines,
                            limbCups = limbCups,
                            headBitmap = headBitmap,
                            headArt = headArt,
                            parsed = parsed,
                            muscleRegions = muscleRegions,
                            stretchedMuscles = stretchedMuscles,
                        )
                    }
                }
            }
        }
        return
    }

    Canvas(
        modifier = modifier
            .aspectRatio(OctopusBodyGeometry.CANVAS_WIDTH / OctopusBodyGeometry.CANVAS_HEIGHT)
            .semantics { contentDescription = a11yDescription }
            .pointerInput(parsed, centeringOffsetX, muscleRegions) {
                detectTapGestures { tap ->
                    val scaleFactor = size.width.toFloat() / OctopusBodyGeometry.CANVAS_WIDTH
                    // Drawing is shifted left by centeringOffsetX — invert for hit-test.
                    val x = (tap.x / scaleFactor + centeringOffsetX).toInt()
                    val y = (tap.y / scaleFactor).toInt()
                    // Muscle plates first (muscle mode), then body-part regions.
                    if (muscleRegions.isNotEmpty()) {
                        val hit = muscleRegions.lastOrNull { (_, path, _) ->
                            spindleHit(path, x.toFloat(), y.toFloat())
                        }
                        if (hit != null) {
                            onMuscleTap(hit.first)
                            return@detectTapGestures
                        }
                    }
                    // Front-most first — see OctopusBodyGeometry.hitTestOrder contract.
                    for ((spec, hit) in parsed.asReversed()) {
                        if (hit.region.contains(x, y)) {
                            onRegionTap(spec.part)
                            return@detectTapGestures
                        }
                    }
                }
            },
    ) {
        val scaleFactor = size.width / OctopusBodyGeometry.CANVAS_WIDTH
        scale(scaleFactor, scaleFactor) {
            translate(left = -centeringOffsetX) {
                drawBody(
                    animatedColors = animatedColors,
                    stretchedMinutes = stretchedMinutes,
                    videoTargets = videoTargets,
                    pulseAlpha = pulseAlpha,
                    fingerTentacles = fingerTentacles,
                    muscleLines = muscleLines,
                    limbCups = limbCups,
                    headBitmap = headBitmap,
                    headArt = headArt,
                    parsed = parsed,
                    muscleRegions = muscleRegions,
                    stretchedMuscles = stretchedMuscles,
                )
            }
        }
    }
}

/** The shared draw block for both layout modes (identical content, different transforms). */
private fun DrawScope.drawBody(
    animatedColors: Map<BodyPart, Color>,
    muscleRegions: List<Triple<Muscle, Path, String>>,
    stretchedMuscles: Set<Muscle>,
    stretchedMinutes: Map<BodyPart, Int>,
    videoTargets: Set<BodyPart>,
    pulseAlpha: Float,
    fingerTentacles: List<Path>,
    muscleLines: List<Path>,
    limbCups: List<OctopusBodyGeometry.DecoCircle>,
    headBitmap: androidx.compose.ui.graphics.ImageBitmap,
    headArt: HeadArtMetrics,
    parsed: List<Pair<OctopusBodyGeometry.RegionSpec, HitTarget>>,
) {
    for ((spec, hit) in parsed) {
                    val stretched = (stretchedMinutes[spec.part] ?: 0) > 0
                    // Phase 18: the idle dome is skipped — the PPQ head art below
                    // IS the head. When the neck is stretched/targeted the fill
                    // still renders (hidden under the art; the feedback glow is
                    // re-traced over the art further down).
                    if (spec.part == BodyPart.NECK && !stretched && spec.part !in videoTargets) {
                        continue
                    }
                    drawRegion(
                        path = hit.path,
                        color = animatedColors[spec.part] ?: RegionIdle,
                        stretched = stretched || spec.part in videoTargets,
                        pulseAlpha = pulseAlpha,
                    )
                }
                drawTentacles(fingerTentacles)
                drawBodyDecorations(muscleLines, limbCups)

                if (muscleRegions.isNotEmpty()) {
                    // Dull the octopus body so the muscle plates read on top: a
                    // dark scrim clipped to the figure silhouette (regions +
                    // finger tentacles). The head art is drawn AFTER this, so
                    // the character's face stays bright.
                    val bodyClip = Path().apply {
                        parsed.forEach { addPath(it.second.path) }
                        fingerTentacles.forEach { addPath(it) }
                    }
                    clipPath(bodyClip) { drawRect(DullScrim) }

                    // Pass 1: dark contour under every plate (fills seams).
                    muscleRegions.forEach { (_, path, _) ->
                        val b = path.getBounds()
                        scale(1.03f, 1.03f, pivot = Offset(b.center.x, b.center.y)) {
                            drawPath(path, color = MuscleEdge, style = Stroke(width = 4f))
                        }
                    }
                    // Pass 2: poster-hue gradient bellies; stretched glow teal.
                    muscleRegions.forEach { (muscle, path, hue) ->
                        val stretched = muscle in stretchedMuscles
                        val (top, bottom) = muscleHueShades(hue)
                        val bounds = path.getBounds()
                        val brush = Brush.verticalGradient(
                            colors = if (stretched) {
                                listOf(StretchTop, StretchBottom)
                            } else {
                                listOf(top, bottom)
                            },
                            startY = bounds.top,
                            endY = bounds.bottom,
                        )
                        if (stretched) {
                            drawPath(path = path, color = StretchGlow, style = Stroke(width = 9f))
                        }
                        drawPath(path = path, brush = brush)
                        drawPath(
                            path = path,
                            color = if (stretched) StretchEdge else MusclePlateEdge,
                            style = Stroke(width = 2f),
                        )
                    }
                }

                // ── PPQ head art composited over the dome ──
                // Fit the art's own dome over the vector dome (uniform scale,
                // dome-center alignment — see the placement constants below). The
                // art's transparent cutout lets the body show between tentacles.
                val s = HEAD_DOME_H * HEAD_MARGIN / headArt.domeH
                drawImage(
                    image = headBitmap,
                    dstOffset = IntOffset(
                        (HEAD_CENTER_X - headArt.domeCx * s).roundToInt(),
                        (HEAD_DOME_CY - headArt.domeCy * s).roundToInt(),
                    ),
                    dstSize = IntSize(
                        (headArt.w * s).roundToInt(),
                        (headArt.h * s).roundToInt(),
                    ),
                )

                // Head-region feedback traces OVER the art (the dome glow under it
                // is hidden by the art's own dome): pulsing ring around the head.
                val neckMinutes = stretchedMinutes[BodyPart.NECK] ?: 0
                if (neckMinutes > 0 || BodyPart.NECK in videoTargets) {
                    val neckPath = parsed.first { it.first.part == BodyPart.NECK }.second.path
                    val color = animatedColors[BodyPart.NECK] ?: RegionIdle
                    repeat(GLOW_LAYERS) { i ->
                        drawPath(
                            path = neckPath,
                            color = color.copy(alpha = 0.30f * pulseAlpha * (1f - i * 0.33f)),
                            style = Stroke(width = 4f + i * 5f, cap = StrokeCap.Round),
                        )
                    }
                }
}

/** Renderable [path] plus its [region] twin used for exact tap hit-testing. */
private data class HitTarget(val path: Path, val region: android.graphics.Region)

/**
 * Phase 24 (feedback round 5) — flip-centering fix, DEVICE-CALIBRATED.
 *
 * The 3D turn rotates around the CANVAS center (500u) — the rotationY pivot —
 * but each side's VISIBLE mass is not centered there: the head arts are
 * asymmetric inside their bitmaps, the limb decorations don't mirror exactly,
 * and the back art rect is off-center by construction (domeCx 531). A geometric
 * union of path bounds UNDER-estimates the deviation (it can't see raster alpha
 * asymmetry) — first on-device iteration proved that: predicted ≈0 for the
 * front while pixel-scan showed +27u.
 *
 * These constants are the MEASURED content-center deviations on a 1080×2316
 * device (docs/art/screenshots/fb5_flip_centered_*.png pixel-scan, canvas node
 * [68,381][1012,1797]): front content center 527u (+27), back 461u (−39). The
 * view draws with translate(−offset) so both visual centers sit on the pivot;
 * re-verify with a pixel-scan if geometry or art is regenerated.
 */
fun sideCenteringOffsetX(side: OctopusBodyGeometry.Side): Float = when (side) {
    OctopusBodyGeometry.Side.FRONT -> FRONT_CENTERING_OFFSET_X
    OctopusBodyGeometry.Side.BACK -> BACK_CENTERING_OFFSET_X
}

/** Front visible-mass deviation from the 500u pivot (positive = right). */
private const val FRONT_CENTERING_OFFSET_X = 27.0f

/**
 * Back visible-mass deviation, positive = drawn RIGHT of the 500u pivot in
 * CANVAS space (the drawing translate runs BEFORE the rotationY mirror, so the
 * canvas-space sign is opposite the on-screen reading). Device-verified two-point
 * calibration: c=0 → back renders 460.8u (39.2u left of pivot, i.e. drawn at
 * 539.2u canvas); c=−38.5 → renders ≈422u (further left — canvas translate of
 * +38.5 mirrored to −38.5 on screen). Solving rendered=500 ⇒ c = +39.
 * (An on-screen-space constant of −38.5 was tried first and moved him the WRONG
 * way — the user caught it immediately.)
 */
private const val BACK_CENTERING_OFFSET_X = 39.0f

private const val HITTEST_PAD = 2

// ── PPQ head-art placement (Phase 18; per-side since Phase 21 addendum) ──
// The dome = the NECK region bounds in the 1000x1500 viewBox
// (x 293–707, y 64–502 → center x 500, center y 283, height 438).
// FRONT art metrics measured on docs/art/octo_head_cutout.png (978x1085,
// make_icon_art.py); BACK art on docs/art/octo_head_back_cutout.png (1092x1152,
// mantle bbox x 192–870, y 12–540 → center 531, 276). If art is regenerated,
// re-measure and update.
//
// FB4 fix (Phase 22): the back art previously used the raw mantle height as
// domeH (525), which scaled the whole art 32% larger than the front — the back
// head + crown tentacles read oversized and shifted. domeH here is the EFFECTIVE
// dome height that yields the SAME uniform scale as the front (438·1.03/621),
// so both sides render the character at identical size; the mantle ellipse is
// a little shorter than the vector dome, which only shows as a soft rim when
// the neck glow ring is up.
internal const val HEAD_CENTER_X = 500f
internal const val HEAD_DOME_CY = 283f
internal const val HEAD_DOME_H = 438f

/** Per-side PPQ head-art placement metrics (raw-art pixel space). */
internal data class HeadArtMetrics(
    val w: Float,
    val h: Float,
    val domeCx: Float,
    val domeCy: Float,
    val domeH: Float,
)

internal val FrontHeadArt = HeadArtMetrics(
    w = 978f,
    h = 1085f,
    domeCx = 488.5f,
    domeCy = 319.5f,
    domeH = 621f,
)

internal val BackHeadArt = HeadArtMetrics(
    w = 1092f,
    h = 1152f,
    domeCx = 531f,
    domeCy = 276f,
    // EFFECTIVE dome height: same on-screen scale as the front art
    // (s = 438·1.03/621 ≈ 0.726 → mantle 528px tall renders ≈ front dome 621px).
    domeH = 621f,
)

/** Small overflow so the art dome fully covers the vector dome (no rim peek). */
internal const val HEAD_MARGIN = 1.03f

/** Geometry y below which suction cups belong to the limbs (head cups ≤ 555,
 *  limb cups ≥ 991 — any threshold in between is safe). */
private const val HEAD_ART_BOTTOM_ROW = 700f

// ── Muscle overlay palette (carried over from the retired écorché MuscleFigureView) ──

/** Dark scrim that dulls the octopus body under the muscle plates. */
private val DullScrim = Color(0xFF10161F).copy(alpha = 0.55f)
private val MuscleEdge = Color(0xFF1E2836)
private val MusclePlateEdge = Color(0x55F2F6FF)

private val StretchTop = Color(0xFF66F2D6)
private val StretchBottom = Color(0xFF38BCA1)
private val StretchEdge = Color(0xFFD8FFF5)
private val StretchGlow = Color(0x7740D8BB)

/**
 * Idle shades: all muscles stay in the light periwinkle/lavender family so
 * unstretched-vs-stretched reads instantly; each group gets a subtle tint
 * drift within that family to keep neighboring plates distinguishable.
 */
private fun muscleHueShades(hue: String): Pair<Color, Color> = when (hue) {
    "red" -> Color(0xFF9FA9D4) to Color(0xFF6B76A6)      // pecs, lats, traps — blue-leaning
    "rust" -> Color(0xFF9C9AD2) to Color(0xFF67679E)     // biceps, hamstrings — violet
    "gold" -> Color(0xFFA8A6D8) to Color(0xFF71709F)     // deltoids — light lavender
    "green" -> Color(0xFF96A4CE) to Color(0xFF62719E)    // abs, erectors — steel
    "violet" -> Color(0xFFA79BD6) to Color(0xFF72649E)   // triceps — purple
    "blue" -> Color(0xFF9BADCE) to Color(0xFF68789E)     // quads, calves, glutes
    "orange" -> Color(0xFFA3A0D0) to Color(0xFF6D6B9C)   // forearms
    "salmon" -> Color(0xFFA1A8D6) to Color(0xFF6D76A2)   // hip flexors, adductors
    "teal" -> Color(0xFF94AAD0) to Color(0xFF61739E)     // shins, soleus
    else -> Color(0xFFADAAD8) to Color(0xFF77749E)       // sand (neck)
}

/** Inscribed-ellipse hit test for muscle plates (generous 1.2 ellipse factor). */
internal fun spindleHit(path: Path, x: Float, y: Float): Boolean {
    val b = path.getBounds()
    if (x < b.left || x > b.right || y < b.top || y > b.bottom) return false
    val rx = b.width / 2f
    val ry = b.height / 2f
    if (rx <= 0f || ry <= 0f) return false
    val nx = (x - b.center.x) / rx
    val ny = (y - b.center.y) / ry
    return nx * nx + ny * ny <= 1.2f
}

/** Idle slate, or teal→green lerped by minutes (capped at [FULL_INTENSITY_MINUTES]). */
private fun regionColor(minutes: Int, isVideoTarget: Boolean = false): Color =
    if (minutes <= 0) {
        if (isVideoTarget) OctoBodyAmber else RegionIdle
    } else {
        val t = min(minutes, FULL_INTENSITY_MINUTES).toFloat() / FULL_INTENSITY_MINUTES
        lerpColor(RegionTeal, RegionGreen, t)
    }

private fun DrawScope.drawRegion(
    path: Path,
    color: Color,
    stretched: Boolean,
    pulseAlpha: Float,
) {
    if (stretched) {
        // Soft glow: three expanding stroked halos, breathing with the pulse.
        repeat(GLOW_LAYERS) { i ->
            drawPath(
                path = path,
                color = color.copy(alpha = 0.30f * pulseAlpha * (1f - i * 0.33f)),
                style = Stroke(width = 4f + i * 5f, cap = StrokeCap.Round),
            )
        }
    }

    // Fill + border.
    drawPath(path = path, color = color)
    drawPath(
        path = path,
        color = if (stretched) Color.White.copy(alpha = 0.55f) else BorderIdle,
        style = Stroke(width = 2.5f, cap = StrokeCap.Round),
    )
}

/** Decorative finger-tentacle clusters at the limb ends — deep-sea slate fill. */
private fun DrawScope.drawTentacles(paths: List<Path>) {
    for (path in paths) {
        drawPath(path = path, color = TentacleDeco)
        drawPath(
            path = path,
            color = BorderIdle,
            style = Stroke(width = 2.5f, cap = StrokeCap.Round),
        )
    }
}

/**
 * Body-only decorations: the face (eyes/pupils/highlights/blush/smile/dome
 * sheen) and the head-tentacle cups are gone with the vector dome (Phase 18 —
 * the PPQ head art carries its own face); muscle lines + limb cups remain.
 */
private fun DrawScope.drawBodyDecorations(
    muscleLines: List<Path>,
    cups: List<OctopusBodyGeometry.DecoCircle>,
) {
    for (line in muscleLines) {
        drawPath(line, MuscleLine, style = Stroke(width = 3f, cap = StrokeCap.Round))
    }
    for (c in cups) {
        drawCircle(Cup, c.radius, Offset(c.cx, c.cy))
    }
}

