private const val GLOW_LAYERS = 3

/** Region color for a given minutes value — part-detail + stats charts (minutes-based). */
fun octoRegionColor(minutes: Int): Color =
    if (minutes <= 0) {
        BodyTierIdleRed
    } else {
        val t = min(minutes, FULL_INTENSITY_MINUTES).toFloat() / FULL_INTENSITY_MINUTES
        lerpColor(OctoBodyTeal, OctoBodyGreen, t)
    }

private const val FULL_INTENSITY_MINUTES = 10

private fun lerpColor(a: Color, b: Color, t: Float): Color = Color(
    red = a.red + (b.red - a.red) * t,
    green = a.green + (b.green - a.green) * t,
    blue = a.blue + (b.blue - a.blue) * t,
    alpha = a.alpha,
)
