#!/usr/bin/env python3
"""Build the transparent BACK-view head cutout from the PPQ back-head art.

Phase 21 addendum: OctopusBodyView composites PPQ art as the man's head. The
front keeps the Phase 10 art (face visible). This script processes the NEW
back-view art (docs/art/octo_head_back_raw.png, generated by
gen_head_art_back.py) the same way make_icon_art.py handles the front:

  - chroma-key the flat navy sea away (silhouette-first, hole classification —
    copied from make_icon_art.py, retuned BG color measured on the back raw)
  - crop to content + 8px margin
  - semi-transparent tentacles below the dome (so the vector back/shoulders
    show through, same as the front on-body variant)
  - measure the teal-dome metrics and print them as Kotlin constants for
    OctopusBodyView's per-side placement

Outputs:
  - docs/art/octo_head_back_cutout.png       (transparent master, archived)
  - app/src/main/res/drawable-nodpi/octo_head_ppq_back.png
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app" / "src" / "main" / "res"
RAW = ROOT / "docs" / "art" / "octo_head_back_raw.png"
CUTOUT = ROOT / "docs" / "art" / "octo_head_back_cutout.png"
OUT = RES / "drawable-nodpi" / "octo_head_ppq_back.png"

# ── Background-removal tuning (measured on octo_head_back_raw.png) ──
BG = np.array([13.0, 35.0, 49.0])
BG_TOL = 14.0
EDGE_LO, EDGE_HI = 6.0, 30.0
EDGE_BAND_PX = 2
KEEP_FG_MIN_SIZE = 5000
KEEP_FG_MIN_DIST = 100.0
POCKET_ROW_FRAC = 0.60   # no face on the back → sea pockets anywhere below dome
POCKET_MAX_DIST = 40.0
POCKET_MIN_SIZE = 150
CREVICE_MAX_DIST = 24.0
DOME_H_FRAC_FALLBACK = 0.58
TENTACLE_ALPHA = 0.40


def remove_background(rgb: Image.Image) -> Image.Image:
    """Same silhouette-first chroma key as make_icon_art.remove_background."""
    arr = np.asarray(rgb).astype(np.float64)
    dist = np.sqrt(((arr - BG) ** 2).sum(axis=2))
    bg_mask = dist < BG_TOL

    fg_seed = ~bg_mask
    flabels, fn = ndimage.label(fg_seed)
    if fn > 1:
        sizes = ndimage.sum(fg_seed, flabels, index=range(1, fn + 1))
        maxdists = ndimage.maximum(dist, flabels, index=range(1, fn + 1))
        keep = (sizes >= KEEP_FG_MIN_SIZE) & (maxdists >= KEEP_FG_MIN_DIST)
        fg_seed = np.concatenate([[False], keep])[flabels]

    solid = ndimage.binary_fill_holes(fg_seed)
    holes = solid & ~fg_seed
    hlabels, hn = ndimage.label(holes)
    removed = np.zeros_like(bg_mask)
    if hn:
        hcents = ndimage.center_of_mass(holes, hlabels, index=range(1, hn + 1))
        hsizes = ndimage.sum(holes, hlabels, index=range(1, hn + 1))
        hmeans = ndimage.mean(dist, hlabels, index=range(1, hn + 1))
        half_h = dist.shape[0] * POCKET_ROW_FRAC
        for j in range(1, hn + 1):
            in_sea_zone = hcents[j - 1][0] >= half_h
            is_sea_colored = hmeans[j - 1] < POCKET_MAX_DIST
            if in_sea_zone and is_sea_colored and hsizes[j - 1] >= POCKET_MIN_SIZE:
                removed |= hlabels == j

    crevice = solid & (dist < CREVICE_MAX_DIST)
    crevice[: int(dist.shape[0] * POCKET_ROW_FRAC), :] = False
    removed |= crevice

    opaque = solid & ~removed
    alpha = np.where(opaque, 255.0, 0.0)
    cut = bg_mask | removed
    near = ndimage.binary_dilation(cut, iterations=EDGE_BAND_PX) & ~cut & opaque
    ramp = np.clip((dist - EDGE_LO) / (EDGE_HI - EDGE_LO), 0.0, 1.0)
    alpha[near] = 255.0 * ramp[near] ** 1.5

    out = np.dstack([arr, alpha]).astype(np.uint8)
    return Image.fromarray(out, "RGBA")


def dome_metrics(img: Image.Image) -> dict:
    """Teal-dome scan: the mantle is the big teal region in the upper half.

    Teal ≈ hue around #3DC9B0-ish: g > r and g > b moderately. Returns the
    tight bbox of the largest teal component + its center/height.
    """
    a = np.asarray(img).astype(np.float64)
    r, g, b, alpha = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    # Teal-green mantle of the back art (measured ~(55,110,115)…(44,101,108)):
    # green clearly above red, at/above blue; navy rim (19,45,62) and purple
    # (42,77,105) both have b > g and are excluded.
    teal = (alpha > 128) & (g > r + 25) & (g >= b - 10) & (g > 80)
    teal[int(a.shape[0] * 0.65):, :] = False  # dome is upper 2/3
    labels, n = ndimage.label(teal)
    if not n:
        return {}
    sizes = ndimage.sum(teal, labels, index=range(1, n + 1))
    j = int(np.argmax(sizes)) + 1
    ys, xs = np.where(labels == j)
    return {
        "x0": int(xs.min()), "x1": int(xs.max()),
        "y0": int(ys.min()), "y1": int(ys.max()),
        "cx": float((xs.min() + xs.max()) / 2),
        "cy": float((ys.min() + ys.max()) / 2),
        "h": float(ys.max() - ys.min()),
    }


def make_on_body(head: Image.Image, dome_bottom_frac: float) -> Image.Image:
    img = head.copy()
    a = np.asarray(img).astype(np.float64)
    alpha = a[..., 3]
    dome_bottom = int(alpha.shape[0] * dome_bottom_frac)
    feather = 60
    rows = np.arange(alpha.shape[0], dtype=np.float64)
    ramp = np.clip((rows - dome_bottom) / feather, 0.0, 1.0)
    scale = 1.0 - ramp * (1.0 - TENTACLE_ALPHA)
    a[..., 3] = alpha * scale[:, None]
    return Image.fromarray(a.astype(np.uint8), "RGBA")


def main() -> int:
    if not RAW.exists():
        sys.exit(f"missing {RAW} — run gen_head_art_back.py first")
    raw = Image.open(RAW).convert("RGB")
    img = remove_background(raw)
    bbox = img.split()[3].getbbox()
    pad = 8
    box = (max(0, bbox[0] - pad), max(0, bbox[1] - pad),
           min(img.width, bbox[2] + pad), min(img.height, bbox[3] + pad))
    img = img.crop(box)
    img.save(CUTOUT)
    print(f"wrote {CUTOUT} ({img.width}x{img.height}, transparent)")

    m = dome_metrics(img)
    if not m:
        print("WARN: teal dome not detected — check the art manually")
        frac = DOME_H_FRAC_FALLBACK
    else:
        frac = m["y1"] / img.height
    out = make_on_body(img, frac)
    out.save(OUT)
    print(f"wrote {OUT} ({out.width}x{out.height})")

    print()
    print("── Kotlin placement constants (OctopusBodyView, BACK side) ──")
    print(f"ART_W_PX_BACK  = {out.width}f")
    print(f"ART_H_PX_BACK  = {out.height}f")
    if m:
        print(f"ART_DOME_CX_PX_BACK = {m['cx']}f")
        print(f"ART_DOME_CY_PX_BACK = {m['cy']}f")
        print(f"ART_DOME_H_PX_BACK  = {m['h']}f")
    print(f"dome_bottom_frac = {frac:.3f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
